#!/usr/bin/env bash
#
# uninstall-kit-craft.sh
#
# Reverses setup-kit-craft.sh:
#   1. Removes the kit-<app> launchers it generated.
#   2. Removes the per-app configs in ~/.config/kit-apps.
#   3. Removes the combined ~/.kit.yml it generated and restores your original
#      ~/.kit.yml from the backup the setup script made (if there was one).
#   4. Removes ~/Documents/Artcraft-In and ~/Documents/Artcraft-Out, but ONLY if
#      they are empty. Your files are never deleted.
#   5. Optionally removes the Kit binary (asks first).
#   6. Optionally removes Kit's saved sessions in ~/.kit (asks first).
#
# It only touches files it can recognize as generated by the setup script.
# Run it as your normal user, not with sudo.
#
# Options:
#   --yes        answer yes to the Kit removal prompts (steps 5 and 6)
#   --keep-kit   do not remove the Kit binary or its data (skips steps 5 and 6)
#   --dry-run    show what would be removed, change nothing
#
# Override folders with the same variables the setup script uses:
#   READ_ROOT, WRITE_ROOT, CONFIG_DIR, BIN_DIR

set -u

READ_ROOT="${READ_ROOT:-$HOME/Documents/Artcraft-In}"
WRITE_ROOT="${WRITE_ROOT:-$HOME/Documents/Artcraft-Out}"
CONFIG_DIR="${CONFIG_DIR:-$HOME/.config/kit-apps}"
BIN_DIR="${BIN_DIR:-$HOME/.local/bin}"
KIT_YML="$HOME/.kit.yml"
KIT_DATA_DIR="$HOME/.kit"

ASSUME_YES=0
KEEP_KIT=0
DRY_RUN=0
for arg in "$@"; do
  case "$arg" in
    --yes) ASSUME_YES=1 ;;
    --keep-kit) KEEP_KIT=1 ;;
    --dry-run) DRY_RUN=1 ;;
    -h|--help) sed -n '2,26p' "$0"; exit 0 ;;
    *) echo "Unknown option: $arg" >&2; exit 2 ;;
  esac
done

RM="[removed]"; RS="[restored]"
if [ "$DRY_RUN" -eq 1 ]; then RM="[would remove]"; RS="[would restore]"; fi

if [ "$(id -u)" -eq 0 ]; then
  echo "Please run this as your normal user, not root/sudo." >&2
  exit 1
fi

# Same app list as the setup script.
APPS=(
  photocraft vectorcraft filmcraft lightcraft pdfcraft effectcraft designcraft
  figcraft texturecraft materialcraft wordcraft soundcraft deckcraft cadcraft
  gridcraft craft-anything
)

say()  { printf '%s\n' "$*"; }
warn() { printf 'WARN: %s\n' "$*" >&2; }

# Runs a command, or just prints it in dry-run mode.
act() {
  if [ "$DRY_RUN" -eq 1 ]; then
    say "     (dry run) $*"
  else
    "$@"
  fi
}

# Yes/no question. $1=prompt  $2=default (y or n).
# Uses the terminal; without one, falls back to the default.
ask_yn() {
  local prompt="$1" def="$2" reply="" hint="y/N"
  [ "$def" = "y" ] && hint="Y/n"
  if [ "$ASSUME_YES" -eq 1 ]; then return 0; fi
  if [ -r /dev/tty ] && [ -w /dev/tty ]; then
    read -r -p "$prompt [$hint]: " reply < /dev/tty > /dev/tty 2>&1 || reply=""
  fi
  reply="${reply:-$def}"
  case "$reply" in y|Y|yes|YES) return 0 ;; *) return 1 ;; esac
}

# A ~/.kit.yml (or backup of one) written by the setup script.
is_generated() {
  [ -f "$1" ] || return 1
  # Current format carries a marker comment; earlier versions are matched by content.
  grep -q 'Generated by setup-kit-craft' "$1" && return 0
  grep -q 'include-core-tools' "$1" && grep -q 'automation-read-root' "$1"
}

# ------------------------------------------------------ 1. Launchers --------

say "Removing generated launchers from $BIN_DIR ..."
removed_any=0
for app in "${APPS[@]}"; do
  f="$BIN_DIR/kit-$app"
  [ -f "$f" ] || continue
  if grep -q 'generated by setup-kit-craft.sh' "$f" 2>/dev/null; then
    act rm -f "$f"
    say "  $RM $f"
    removed_any=1
  else
    say "  [kept]    $f (not generated by the setup script)"
  fi
done
[ "$removed_any" -eq 0 ] && say "  (none found)"

# -------------------------------------------------- 2. Per-app configs ------

say ""
say "Removing per-app configs from $CONFIG_DIR ..."
removed_any=0
for app in "${APPS[@]}"; do
  for name in "$app.yml" "$app-connect.yml" "$app-live.yml" "$app-app.log" "$app-control.token"; do
    f="$CONFIG_DIR/$name"
    [ -f "$f" ] || continue
    act rm -f "$f"
    say "  $RM $f"
    removed_any=1
  done
done
[ "$removed_any" -eq 0 ] && say "  (none found)"
if [ -d "$CONFIG_DIR" ]; then
  if [ "$DRY_RUN" -eq 1 ]; then
    say "     (dry run) would remove $CONFIG_DIR if empty"
  elif rmdir "$CONFIG_DIR" 2>/dev/null; then
    say "  $RM $CONFIG_DIR (was empty)"
  else
    say "  [kept]    $CONFIG_DIR (contains other files)"
  fi
fi

# ----------------------------------------------- 3. Combined ~/.kit.yml -----

say ""
say "Checking $KIT_YML ..."
target_gone=0
if [ -f "$KIT_YML" ]; then
  if is_generated "$KIT_YML"; then
    act rm -f "$KIT_YML"
    say "  $RM generated $KIT_YML"
    target_gone=1
  else
    say "  [kept]    $KIT_YML (not generated by the setup script; left untouched)"
  fi
else
  target_gone=1
fi

if [ "$target_gone" -eq 1 ]; then
  # Backups are named ~/.kit.yml.bak.<timestamp>. If the setup script ran more
  # than once, newer backups may themselves be generated files, so the original
  # is the oldest backup that does NOT look generated.
  genuine=""
  while IFS= read -r bak; do
    [ -n "$bak" ] || continue
    if is_generated "$bak"; then
      act rm -f "$bak"
      say "  $RM generated backup $bak"
    elif [ -z "$genuine" ]; then
      genuine="$bak"
    else
      say "  [kept]    $bak (additional backup of your own config)"
    fi
  done < <(ls -1 "$KIT_YML".bak.* 2>/dev/null | sort)

  if [ -n "$genuine" ]; then
    act mv "$genuine" "$KIT_YML"
    say "  $RS your original config from $genuine"
  fi
fi

# ------------------------------------------------------- 4. Folders ---------

say ""
say "Removing input/output folders if empty ..."
for d in "$READ_ROOT" "$WRITE_ROOT"; do
  [ -d "$d" ] || continue
  if [ "$DRY_RUN" -eq 1 ]; then
    if [ -z "$(ls -A "$d" 2>/dev/null)" ]; then
      say "  (dry run) would remove empty folder $d"
    else
      say "  (dry run) would keep $d (contains files)"
    fi
  elif rmdir "$d" 2>/dev/null; then
    say "  $RM $d (was empty)"
  else
    say "  [kept]    $d (contains files; delete it yourself if you want it gone)"
  fi
done

# ----------------------------------------------------- 5. Kit binary --------

if [ "$KEEP_KIT" -eq 0 ]; then
  say ""
  say "Checking the Kit binary ..."
  kit_path="$(type -P kit 2>/dev/null || true)"
  if [ -z "$kit_path" ]; then
    say "  Kit is not on PATH; nothing to remove."
  else
    # Kit's install script puts a plain file named 'kit' in one of these.
    case "$kit_path" in
      "$HOME/.local/bin/kit"|"$HOME/bin/kit"|/usr/local/bin/kit)
        if [ -L "$kit_path" ]; then
          installed_by_script=0
        else
          installed_by_script=1
        fi ;;
      *) installed_by_script=0 ;;
    esac

    if [ "$installed_by_script" -eq 1 ]; then
      say "  Found Kit at $kit_path (matches the official install script)."
      say "  Note: if you had Kit installed before running the setup script, you may want to keep it."
      if ask_yn "  Remove $kit_path?" n; then
        if [ "$DRY_RUN" -eq 1 ]; then
          say "     (dry run) rm -f $kit_path"
        elif rm -f "$kit_path" 2>/dev/null && [ ! -e "$kit_path" ]; then
          say "  $RM $kit_path"
        else
          warn "Could not remove $kit_path (permission denied). Run:  sudo rm $kit_path"
        fi
      else
        say "  [kept]    $kit_path"
      fi
    else
      say "  Kit is at $kit_path, which does not look like the official install script's location,"
      say "  so it was left alone. If it came from another installer, remove it that way, e.g.:"
      say "    npm uninstall -g @mark3labs/kit"
      say "    rm \"\$(go env GOPATH)/bin/kit\"     # if installed with go install"
    fi
  fi

  # ------------------------------------------------ 6. Kit saved data -------
  if [ -d "$KIT_DATA_DIR" ]; then
    say ""
    say "Kit's data folder exists: $KIT_DATA_DIR"
    say "  (it holds saved chat sessions, which may include your prompts and tool results)"
    if ask_yn "  Delete $KIT_DATA_DIR?" n; then
      act rm -rf "$KIT_DATA_DIR"
      say "  $RM $KIT_DATA_DIR"
    else
      say "  [kept]    $KIT_DATA_DIR"
    fi
  fi
fi

say ""
say "Done. Nothing was changed on the Ollama PC; remove the model there with 'ollama rm <model>' if you want."
